from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from road_damage.model import ModelLoadError, load_road_damage_model, resolve_inference_device  # noqa: E402
from scripts.train import validate_dataset_yaml  # noqa: E402


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Evaluate the trained four-class RDD2022 detector on the held-out validation split."
    )
    parser.add_argument("--weights", type=Path, default=ROOT / "models/road_damage_yolov8n.pt")
    parser.add_argument("--data", type=Path, default=ROOT / "data/rdd2022_yolo/data.yaml")
    parser.add_argument("--imgsz", type=int, default=640)
    parser.add_argument("--device", default="", help="For example 0 for CUDA, cpu, or blank for auto-detect.")
    args = parser.parse_args()

    weights = args.weights.expanduser().resolve()
    data_path = args.data.expanduser().resolve()
    if args.imgsz < 32:
        parser.error("--imgsz must be at least 32.")
    try:
        validate_dataset_yaml(data_path)
        model = load_road_damage_model(weights)
        device = resolve_inference_device(args.device)
    except (ValueError, ModelLoadError) as exc:
        parser.error(str(exc))

    options = {"data": str(data_path), "imgsz": args.imgsz, "split": "val", "plots": True}
    if device is not None:
        options["device"] = device
    metrics = model.val(**options)
    print(f"Validation results saved in: {getattr(metrics, 'save_dir', 'Ultralytics run directory')}")
    print("Use only the metrics generated by this run in project reports.")


if __name__ == "__main__":
    main()

